log = logging.getLogger(__name__)
RETRO_CHUNK = 100_000
BUILTIN_TABLES: tuple[tuple[str, LogSource], ...] = tuple(
    (ls.table_name, ls) for ls in (WEBSERVER, LINUX_AUTH, ECS, GENERIC_JSON)
)


def register_functions(conn: sqlite3.Connection) -> None:
    conn.create_function("regexp", 2, sql_regexp, deterministic=True)


@dataclass(slots=True)
class ReloadReport:
    loaded: int = 0
    errors: int = 0
    removed: int = 0
    filters: int = 0
    file_errors: dict[str, str] = field(default_factory=dict)


@dataclass(slots=True)
class RunReport:
    rules_run: int = 0
    correlations_run: int = 0
    suppressed: int = 0
    result: RecordResult = field(default_factory=RecordResult)
    errors: dict[str, str] = field(default_factory=dict)


def rule_sources(settings: Settings) -> list[tuple[Path, str]]:
    sources: list[tuple[Path, str]] = []
    builtin = builtin_rules_dir()
    if settings.builtin_rules and builtin is not None:
        sources.append((builtin, "builtin"))
    sources.append((settings.rules_path, "user"))
    return sources


def rule_test_dirs(settings: Settings) -> list[Path]:
    dirs = [settings.rules_path / "tests"]
    builtin = builtin_tests_dir()
    if settings.builtin_rules and builtin is not None:
        dirs.append(builtin)
    return dirs


def table_catalog(conn: sqlite3.Connection) -> list[tuple[str, LogSource]]:
    catalog = dict(BUILTIN_TABLES)
    for row in conn.execute("SELECT table_name, category, product, service FROM event_tables"):
        catalog[row[0]] = LogSource(row[1], row[2], row[3])
    return sorted(catalog.items())


class DetectionEngine:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self._lock = threading.RLock()
        self._compiled: dict[tuple[str, str], CompiledRule | str] = {}  # value: query or error
        self._filters: list[str] = []  # YAML of valid Sigma filters
        self._compiled_corr: dict[str, CompiledCorrelation | str] = {}

    # ---------------------------------------------------------------- loading

    def reload(self, conn: sqlite3.Connection, actor: str | None = None) -> ReloadReport:
        result = load_rules(rule_sources(self.settings))
        report = ReloadReport(file_errors=dict(result.file_errors))
        now = now_ms()
        with self._lock, transaction(conn):
            previous = {
                r[0]: (bool(r[1]), r[2])
                for r in conn.execute("SELECT id, enabled, sha256 FROM rules")
            }
            for lr in result.rules:
                enabled = previous.get(lr.id, (self._default_enabled(lr), ""))[0]
                self._upsert(conn, lr, enabled, now, actor)
                report.loaded += 1
                report.errors += lr.load_error is not None
            current = {lr.id for lr in result.rules}
            gone = [rid for rid in previous if rid not in current]
            conn.executemany("DELETE FROM rules WHERE id = ?", [(rid,) for rid in gone])
            report.removed = len(gone)
            conn.execute("DELETE FROM sigma_filters")
            conn.executemany(
                "INSERT INTO sigma_filters (id, title, path, yaml, sha256, load_error, loaded_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?)",
                [
                    (f.id, f.title, f.path, f.yaml, f.sha256, f.load_error, now)
                    for f in result.filters
                ],
            )
            self._filters = [f.yaml for f in result.filters if f.load_error is None]
            report.filters = len(result.filters)
            conn.execute("DELETE FROM rule_load_errors")
            conn.executemany(
                "INSERT INTO rule_load_errors (path, error, seen_at) VALUES (?, ?, ?)",
                [(p, e, now) for p, e in result.file_errors.items()],
            )
            self._compiled.clear()
            self._compiled_corr.clear()
            self._mark_correlation_only(conn)
        self.check_compilation(conn)
        log.info(
            "rules reloaded",
            extra={
                "loaded": report.loaded,
                "errors": report.errors,
                "file_errors": len(report.file_errors),
            },
        )
        return report

    @staticmethod
    def _resolve(conn: sqlite3.Connection, ref: str) -> sqlite3.Row | None:
        row: sqlite3.Row | None = conn.execute(
            "SELECT * FROM rules WHERE id = ? OR name = ? ORDER BY id = ? DESC LIMIT 1",
            (ref, ref, ref),
        ).fetchone()
        return row

    def _mark_correlation_only(self, conn: sqlite3.Connection) -> None:
        """Sigma v2: rules referenced by a correlation do not alert on their own unless
        some enabled correlation that uses them says ``generate: true``."""
        only: set[str] = set()
        keep: set[str] = set()
        for (text,) in conn.execute(
            "SELECT yaml FROM rules WHERE kind = 'correlation' AND enabled = 1 "
            "AND (load_error IS NULL OR load_error LIKE 'cannot compile%')"
        ).fetchall():
            doc = yaml.safe_load(text) or {}
            generate = bool((doc.get("correlation") or {}).get("generate", False))
            for ref in references(text):
                row = self._resolve(conn, ref)
                if row is not None:
                    (keep if generate else only).add(row["id"])
        conn.execute("UPDATE rules SET correlation_only = 0")
        conn.executemany(
            "UPDATE rules SET correlation_only = 1 WHERE id = ?", [(rid,) for rid in only - keep]
        )

    @staticmethod
    def _loaded(row: sqlite3.Row) -> LoadedRule:
        return LoadedRule(
            id=row["id"],
            title=row["title"],
            kind=row["kind"],
            origin=row["origin"],
            path=row["path"],
            yaml=row["yaml"],
            sha256=row["sha256"],
            name=row["name"],
            logsource=json.loads(row["logsource"]),
            load_error=row["load_error"],
        )

    @staticmethod
    def _default_enabled(lr: LoadedRule) -> bool:
        return lr.status not in ("deprecated", "unsupported")

    @staticmethod
    def _upsert(
        conn: sqlite3.Connection, lr: LoadedRule, enabled: bool, now: int, actor: str | None
    ) -> None:
        conn.execute(
            "INSERT INTO rules (id, title, kind, origin, path, level, status, description, "
            "author, tags, logsource, yaml, sha256, enabled, load_error, warnings, loaded_at, "
            "updated_by, name) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) "
            "ON CONFLICT (id) DO UPDATE SET title = excluded.title, kind = excluded.kind, "
            "origin = excluded.origin, path = excluded.path, level = excluded.level, "
            "status = excluded.status, description = excluded.description, "
            "author = excluded.author, tags = excluded.tags, logsource = excluded.logsource, "
            "yaml = excluded.yaml, sha256 = excluded.sha256, load_error = excluded.load_error, "
            "warnings = excluded.warnings, loaded_at = excluded.loaded_at, name = excluded.name, "
            "test_status = CASE WHEN rules.sha256 = excluded.sha256 THEN rules.test_status "
            "ELSE NULL END",
            (
                lr.id,
                lr.title,
                lr.kind,
                lr.origin,
                lr.path,
                lr.level,
                lr.status,
                lr.description,
                lr.author,
                json.dumps(lr.tags),
                json.dumps(lr.logsource),
                lr.yaml,
                lr.sha256,
                int(enabled),
                lr.load_error,
                json.dumps(lr.warnings),
                now,
                actor,
                lr.name,
            ),
        )

    def check_compilation(self, conn: sqlite3.Connection) -> None:
        """Compile every valid detection rule for its tables now, so errors show up
        on the Rules page right after a reload instead of at the next ingest."""
        catalog = table_catalog(conn)
        rows = conn.execute(
            "SELECT id, yaml, logsource FROM rules WHERE kind = 'detection' "
            "AND (load_error IS NULL OR load_error LIKE 'cannot compile%')"
        ).fetchall()
        updates: list[tuple[str | None, str]] = []
        for rule_id, yaml_text, logsource in rows:
            tables = tables_for(json.loads(logsource), catalog)
            error = None
            for table in tables:
                compiled = self._compile(rule_id, yaml_text, table)
                if isinstance(compiled, str):
                    error = f"cannot compile for {table}: {compiled}"
                    break
            updates.append((error, rule_id))
        with transaction(conn):
            conn.executemany("UPDATE rules SET load_error = ? WHERE id = ?", updates)
        # Correlations second: they depend on their base rules' (now saved) status.
        corr_updates: list[tuple[str | None, str]] = []
        for rule_id, yaml_text in conn.execute(
            "SELECT id, yaml FROM rules WHERE kind = 'correlation' "
            "AND (load_error IS NULL OR load_error LIKE 'cannot compile%')"
        ).fetchall():
            corr = self._compile_corr(conn, rule_id, yaml_text)
            corr_error = f"cannot compile correlation: {corr}" if isinstance(corr, str) else None
            corr_updates.append((corr_error, rule_id))
        with transaction(conn):
            conn.executemany("UPDATE rules SET load_error = ? WHERE id = ?", corr_updates)

    def _compile(self, rule_id: str, yaml_text: str, table: str) -> CompiledRule | str:
        key = (rule_id, table)
        with self._lock:
            if key not in self._compiled:
                try:
                    self._compiled[key] = compile_detection(yaml_text, table, self._filters)
                except CompileError as exc:
                    self._compiled[key] = str(exc)
            return self._compiled[key]

    def _bases(self, conn: sqlite3.Connection, corr_yaml: str) -> list[BaseRule] | str:
        catalog = table_catalog(conn)
        present = set(EventStore(conn).event_tables())
        bases: list[BaseRule] = []
        for ref in references(corr_yaml):
            row = self._resolve(conn, ref)
            if row is None:
                return f"referenced rule {ref!r} is not loaded"
            if row["kind"] != "detection":
                return f"referenced rule {ref!r} is not a detection rule"
            if row["load_error"]:
                return f"referenced rule {ref!r} has errors"
            logsource = json.loads(row["logsource"])
            tables = tables_for(logsource, catalog)
            if not tables:
                return f"referenced rule {ref!r} has no event table for its log source"
            table = next((t for t in tables if t in present), tables[0])
            bases.append(BaseRule(row["id"], row["name"], row["yaml"], table, logsource))
        return bases

    def _compile_corr(
        self, conn: sqlite3.Connection, rule_id: str, yaml_text: str
    ) -> CompiledCorrelation | str:
        with self._lock:
            if rule_id not in self._compiled_corr:
                bases = self._bases(conn, yaml_text)
                if isinstance(bases, str):
                    self._compiled_corr[rule_id] = bases
                else:
                    try:
                        self._compiled_corr[rule_id] = compile_correlation(
                            yaml_text, bases, self._filters
                        )
                    except CompileError as exc:
                        self._compiled_corr[rule_id] = str(exc)
            return self._compiled_corr[rule_id]

    def compiled_correlation_for(
        self, conn: sqlite3.Connection, rule_id: str
    ) -> CompiledCorrelation | str | None:
        row = conn.execute("SELECT yaml, kind FROM rules WHERE id = ?", (rule_id,)).fetchone()
        if row is None or row["kind"] != "correlation":
            return None
        return self._compile_corr(conn, rule_id, row["yaml"])

    def set_enabled(
        self, conn: sqlite3.Connection, rule_id: str, enabled: bool, actor: str | None
    ) -> None:
        with transaction(conn):
            conn.execute(
                "UPDATE rules SET enabled = ?, updated_by = ? WHERE id = ?",
                (int(enabled), actor, rule_id),
            )
            self._mark_correlation_only(conn)

    def compiled_for(self, conn: sqlite3.Connection, rule_id: str) -> list[CompiledRule | str]:
        row = conn.execute(
            "SELECT yaml, logsource, kind FROM rules WHERE id = ?", (rule_id,)
        ).fetchone()
        if row is None or row["kind"] != "detection":
            return []
        tables = tables_for(json.loads(row["logsource"]), table_catalog(conn))
        return [self._compile(rule_id, row["yaml"], t) for t in tables]

    # ---------------------------------------------------------------- running

    def _runnable(self, conn: sqlite3.Connection, rule_id: str | None = None) -> list[sqlite3.Row]:
        sql = (
            "SELECT id, title, level, tags, yaml, logsource FROM rules WHERE kind = 'detection' "
            "AND load_error IS NULL"
        )
        if rule_id is None:
            return conn.execute(sql + " AND enabled = 1 AND correlation_only = 0").fetchall()
        return conn.execute(sql + " AND id = ?", (rule_id,)).fetchall()

    def _ensure_columns(self, conn: sqlite3.Connection, compiled: CompiledRule) -> None:
        """A rule may reference fields this table has never seen; add them as empty
        columns so the query runs (and NOT/exists conditions behave correctly)."""
        store = EventStore(conn)
        existing = store.table_columns(compiled.table)
        missing = [f for f in compiled.fields if f.lower() not in existing]
        if missing:
            with transaction(conn):
                for f in missing:
                    conn.execute(
                        f"ALTER TABLE {quote_ident(compiled.table)} "
                        f"ADD COLUMN {quote_ident(f)} TEXT COLLATE NOCASE"
                    )

    def _matches(
        self,
        conn: sqlite3.Connection,
        compiled: CompiledRule,
        lo: int,
        hi: int,
        suppressions: list[Suppression],
        suppressed: dict[int, int],
    ) -> list[Match]:
        cursor = conn.execute(
            f"SELECT * FROM ({compiled.sql}) WHERE {ID} BETWEEN ? AND ?",
            (lo, hi),
        )
        out = []
        for row in cursor:
            if suppressions:
                values = {k: row[k] for k in row.keys()}  # noqa: SIM118 - sqlite3.Row
                hit = next((s for s in suppressions if s.matches(values)), None)
                if hit is not None:
                    suppressed[hit.id] = suppressed.get(hit.id, 0) + 1
                    continue
            out.append(Match(compiled.table, row[ID], row["tl_ts"], entities_from_row(row)))
        return out

    def _run_rule(
        self,
        conn: sqlite3.Connection,
        rule: sqlite3.Row,
        ranges: dict[str, list[tuple[int, int]]],
        origin: str,
        report: RunReport,
    ) -> None:
        catalog = table_catalog(conn)
        existing = set(EventStore(conn).event_tables())
        info = RuleInfo(
            rule["id"], rule["title"], rule["level"] or "medium", json.loads(rule["tags"])
        )
        window = self.settings.alert_throttle_minutes * 60_000
        suppressions = active_for_rule(conn, rule["id"])
        suppressed: dict[int, int] = {}
        for table in tables_for(json.loads(rule["logsource"]), catalog):
            if table not in ranges or table not in existing:
                continue
            compiled = self._compile(rule["id"], rule["yaml"], table)
            if isinstance(compiled, str):
                report.errors[rule["id"]] = compiled
                continue
            self._ensure_columns(conn, compiled)
            for lo, hi in ranges[table]:  # one range at a time keeps memory bounded
                try:
                    matched = self._matches(conn, compiled, lo, hi, suppressions, suppressed)
                except sqlite3.Error as exc:
                    report.errors[rule["id"]] = f"query failed on {table}: {exc}"
                    log.warning("rule query failed", extra={"rule": rule["id"], "error": str(exc)})
                    break
                if matched:
                    with transaction(conn):
                        report.result.merge(record_matches(conn, info, matched, window, origin))
        if suppressed:
            with transaction(conn):
                record_hits(conn, rule["id"], suppressed)
            report.suppressed += sum(suppressed.values())
        report.rules_run += 1

    def run_ranges(
        self, conn: sqlite3.Connection, chunks: Iterable[tuple[str, int, int]]
    ) -> RunReport:
        """Detection on newly ingested rows (``(table, min_id, max_id)`` chunks)."""
        register_functions(conn)
        ranges: dict[str, list[tuple[int, int]]] = {}
        for table, lo, hi in chunks:
            ranges.setdefault(table, []).append((lo, hi))
        report = RunReport()
        if not ranges:
            return report
        for rule in self._runnable(conn):
            self._run_rule(conn, rule, ranges, "ingest", report)
        self._run_correlations(conn, ranges, report)
        return report

    def _time_bounds(
        self, conn: sqlite3.Connection, ranges: dict[str, list[tuple[int, int]]]
    ) -> dict[str, tuple[int, int]]:
        bounds: dict[str, tuple[int, int]] = {}
        for table, spans in ranges.items():
            for lo, hi in spans:
                tmin, tmax = conn.execute(
                    f"SELECT min(tl_ts), max(tl_ts) FROM {quote_ident(table)} "
                    f"WHERE {ID} BETWEEN ? AND ?",
                    (lo, hi),
                ).fetchone()
                if tmin is None:
                    continue
                old = bounds.get(table)
                bounds[table] = (min(tmin, old[0]), max(tmax, old[1])) if old else (tmin, tmax)
        return bounds

    def _run_correlations(
        self,
        conn: sqlite3.Connection,
        ranges: dict[str, list[tuple[int, int]]],
        report: RunReport,
        only: str | None = None,
        origin: str = "ingest",
    ) -> None:
        """Correlations whose source tables received new rows, over the new rows' time
        range widened backwards by the rule's timespan."""
        sql = (
            "SELECT id, title, level, tags, yaml FROM rules WHERE kind = 'correlation' "
            "AND load_error IS NULL"
        )
        rows = (
            conn.execute(sql + " AND id = ?", (only,))
            if only
            else conn.execute(sql + " AND enabled = 1")
        ).fetchall()
        if not rows:
            return
        bounds = self._time_bounds(conn, ranges)
        window = self.settings.alert_throttle_minutes * 60_000
        for row in rows:
            compiled = self._compile_corr(conn, row["id"], row["yaml"])
            if isinstance(compiled, str):
                report.errors[row["id"]] = compiled
                continue
            touched = [t for t in set(compiled.source_tables.values()) if t in bounds]
            if not touched:
                continue
            start = min(bounds[t][0] for t in touched) - compiled.timespan_ms
            end = max(bounds[t][1] for t in touched)
            info = RuleInfo(
                row["id"], row["title"], row["level"] or "medium", json.loads(row["tags"])
            )
            try:
                result = run_correlation(conn, compiled, info, start, end, window, origin)
            except sqlite3.Error as exc:
                report.errors[row["id"]] = f"correlation query failed: {exc}"
                log.warning("correlation failed", extra={"rule": row["id"], "error": str(exc)})
                continue
            report.result.merge(result)
            report.correlations_run += 1

    def retro_hunt(self, conn: sqlite3.Connection, rule_id: str) -> RunReport:
        """Run one rule (enabled or not) over every stored event."""
        register_functions(conn)
        report = RunReport()
        kind = conn.execute("SELECT kind FROM rules WHERE id = ?", (rule_id,)).fetchone()
        if kind is not None and kind[0] == "correlation":
            everything: dict[str, list[tuple[int, int]]] = {}
            for table in EventStore(conn).event_tables():
                lo, hi = conn.execute(
                    f"SELECT min({ID}), max({ID}) FROM {quote_ident(table)}"
                ).fetchone()
                if lo is not None:
                    everything[table] = [(lo, hi)]
            self._run_correlations(conn, everything, report, only=rule_id, origin="retro")
            if not report.correlations_run and rule_id not in report.errors:
                report.errors[rule_id] = "no data for this correlation's log sources, or errors"
            return report
        rows = self._runnable(conn, rule_id)
        if not rows:
            report.errors[rule_id] = "rule not found, not a detection rule, or has errors"
            return report
        ranges: dict[str, list[tuple[int, int]]] = {}
        for table in EventStore(conn).event_tables():
            lo, hi = conn.execute(
                f"SELECT min({ID}), max({ID}) FROM {quote_ident(table)}"
            ).fetchone()
            if lo is None:
                continue
            ranges[table] = [
                (s, min(hi, s + RETRO_CHUNK - 1)) for s in range(lo, hi + 1, RETRO_CHUNK)
            ]
        self._run_rule(conn, rows[0], ranges, "retro", report)
        return report

    # ---------------------------------------------------------------- rule tests

    def run_tests(self, conn: sqlite3.Connection, rule_id: str | None = None) -> list[Any]:
        """Run the tp/tn fixtures of every rule (or one) and store the outcome."""
        from threatlens.detection.testing import run_rule_test  # noqa: PLC0415 - import cycle

        sql = "SELECT * FROM rules" + (" WHERE id = ?" if rule_id else "")
        rows = conn.execute(sql, (rule_id,) if rule_id else ()).fetchall()
        dirs = rule_test_dirs(self.settings)
        results = []
        for row in rows:
            lr = self._loaded(row)
            bases = None
            if lr.kind == "correlation":
                bases = [
                    self._loaded(b)
                    for ref in references(lr.yaml)
                    if (b := self._resolve(conn, ref)) is not None and b["kind"] == "detection"
                ]
            results.append(run_rule_test(lr, dirs, self._filters, bases))
        now = now_ms()
        with transaction(conn):
            conn.executemany(
                "UPDATE rules SET test_status = ?, test_message = ?, tested_at = ? WHERE id = ?",
                [(r.status, "; ".join(r.messages) or None, now, r.rule_id) for r in results],
            )
        return results
