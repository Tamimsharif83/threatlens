"""The detection engine: load rules, compile them per event table, run them.

* ``reload`` reads the rule files, stores them in the ``rules`` table (keeping
  each rule's enabled flag and counters) and drops compiled queries.
* ``run_ranges`` runs every enabled detection rule over newly ingested rows
  (the id ranges of an ingest batch) — this is "detection on every batch".
* ``retro_hunt`` runs one rule over all stored events.

Rule SQL is generated by pySigma-backend-sqlite and executed read-only over the
event tables; values in rules are embedded by the backend as escaped literals,
and every ThreatLens-supplied value is a bound parameter.
"""

