"""The detection engine: load rules, compile them per event table, run them.

* ``reload`` reads the rule files, stores them in the ``rules`` table (keeping
  each rule's enabled flag and counters) and drops compiled queries.
* ``run_ranges`` runs every enabled detection rule over newly ingested rows
  (the id ranges of an ingest batch) — this is "detection on every batch".
* ``retro_hunt`` runs one rule over all stored events.

Rule SQL is generated by pySigma-backend-sqlite and executed read-only over the
event tables; values in rules are embedded by the backend as escaped literals,
and every ThreatLens-supplied value is a bound parameter.
"""

from __future__ import annotations

import json
import logging
import sqlite3
import threading
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from threatlens.alerts.store import Match, RecordResult, RuleInfo, entities_from_row, record_matches
from threatlens.config import Settings
from threatlens.detection.compiler import (
    CompiledRule,
    CompileError,
    compile_detection,
    sql_regexp,
    tables_for,
)
from threatlens.detection.loader import (
    LoadedRule,
    builtin_rules_dir,
    builtin_tests_dir,
    load_rules,
)
from threatlens.normalize.schema import ECS, GENERIC_JSON, LINUX_AUTH, WEBSERVER, LogSource
from threatlens.storage.db import transaction
from threatlens.storage.events import ID, EventStore, quote_ident
from threatlens.timeutil import now_ms

log = logging.getLogger(__name__)
RETRO_CHUNK = 100_000
BUILTIN_TABLES: tuple[tuple[str, LogSource], ...] = tuple(
    (ls.table_name, ls) for ls in (WEBSERVER, LINUX_AUTH, ECS, GENERIC_JSON)
)


def register_functions(conn: sqlite3.Connection) -> None:
    conn.create_function("regexp", 2, sql_regexp, deterministic=True)


@dataclass(slots=True)
class ReloadReport:
    loaded: int = 0
    errors: int = 0
    removed: int = 0
    file_errors: dict[str, str] = field(default_factory=dict)


@dataclass(slots=True)
class RunReport:
    rules_run: int = 0
    result: RecordResult = field(default_factory=RecordResult)
    errors: dict[str, str] = field(default_factory=dict)


def rule_sources(settings: Settings) -> list[tuple[Path, str]]:
    sources: list[tuple[Path, str]] = []
    builtin = builtin_rules_dir()
    if settings.builtin_rules and builtin is not None:
        sources.append((builtin, "builtin"))
    sources.append((settings.rules_path, "user"))
    return sources


def rule_test_dirs(settings: Settings) -> list[Path]:
    dirs = [settings.rules_path / "tests"]
    builtin = builtin_tests_dir()
    if settings.builtin_rules and builtin is not None:
        dirs.append(builtin)
    return dirs


def table_catalog(conn: sqlite3.Connection) -> list[tuple[str, LogSource]]:
    catalog = dict(BUILTIN_TABLES)
    for row in conn.execute("SELECT table_name, category, product, service FROM event_tables"):
        catalog[row[0]] = LogSource(row[1], row[2], row[3])
    return sorted(catalog.items())


class DetectionEngine:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self._lock = threading.RLock()
        self._compiled: dict[tuple[str, str], CompiledRule | str] = {}  # value: query or error

    # ---------------------------------------------------------------- loading

    def reload(self, conn: sqlite3.Connection, actor: str | None = None) -> ReloadReport:
        result = load_rules(rule_sources(self.settings))
        report = ReloadReport(file_errors=dict(result.file_errors))
        now = now_ms()
        with self._lock, transaction(conn):
            previous = {
                r[0]: (bool(r[1]), r[2])
                for r in conn.execute("SELECT id, enabled, sha256 FROM rules")
            }
            for lr in result.rules:
                enabled = previous.get(lr.id, (self._default_enabled(lr), ""))[0]
                self._upsert(conn, lr, enabled, now, actor)
                report.loaded += 1
                report.errors += lr.load_error is not None
            current = {lr.id for lr in result.rules}
            gone = [rid for rid in previous if rid not in current]
            conn.executemany("DELETE FROM rules WHERE id = ?", [(rid,) for rid in gone])
            report.removed = len(gone)
            conn.execute("DELETE FROM rule_load_errors")
            conn.executemany(
                "INSERT INTO rule_load_errors (path, error, seen_at) VALUES (?, ?, ?)",
                [(p, e, now) for p, e in result.file_errors.items()],
            )
            self._compiled.clear()
        self.check_compilation(conn)
        log.info(
            "rules reloaded",
            extra={
                "loaded": report.loaded,
                "errors": report.errors,
                "file_errors": len(report.file_errors),
            },
        )
        return report

    @staticmethod
    def _default_enabled(lr: LoadedRule) -> bool:
        return lr.status not in ("deprecated", "unsupported")

    @staticmethod
    def _upsert(
        conn: sqlite3.Connection, lr: LoadedRule, enabled: bool, now: int, actor: str | None
    ) -> None:
        conn.execute(
            "INSERT INTO rules (id, title, kind, origin, path, level, status, description, "
            "author, tags, logsource, yaml, sha256, enabled, load_error, warnings, loaded_at, "
            "updated_by) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) "
            "ON CONFLICT (id) DO UPDATE SET title = excluded.title, kind = excluded.kind, "
            "origin = excluded.origin, path = excluded.path, level = excluded.level, "
            "status = excluded.status, description = excluded.description, "
            "author = excluded.author, tags = excluded.tags, logsource = excluded.logsource, "
            "yaml = excluded.yaml, sha256 = excluded.sha256, load_error = excluded.load_error, "
            "warnings = excluded.warnings, loaded_at = excluded.loaded_at, "
            "test_status = CASE WHEN rules.sha256 = excluded.sha256 THEN rules.test_status "
            "ELSE NULL END",
            (
                lr.id,
                lr.title,
                lr.kind,
                lr.origin,
                lr.path,
                lr.level,
                lr.status,
                lr.description,
                lr.author,
                json.dumps(lr.tags),
                json.dumps(lr.logsource),
                lr.yaml,
                lr.sha256,
                int(enabled),
                lr.load_error,
                json.dumps(lr.warnings),
                now,
                actor,
            ),
        )

    def check_compilation(self, conn: sqlite3.Connection) -> None:
        """Compile every valid detection rule for its tables now, so errors show up
        on the Rules page right after a reload instead of at the next ingest."""
        catalog = table_catalog(conn)
        rows = conn.execute(
            "SELECT id, yaml, logsource FROM rules WHERE kind = 'detection' "
            "AND (load_error IS NULL OR load_error LIKE 'cannot compile%')"
        ).fetchall()
        updates: list[tuple[str | None, str]] = []
        for rule_id, yaml_text, logsource in rows:
            tables = tables_for(json.loads(logsource), catalog)
            error = None
            for table in tables:
                compiled = self._compile(rule_id, yaml_text, table)
                if isinstance(compiled, str):
                    error = f"cannot compile for {table}: {compiled}"
                    break
            updates.append((error, rule_id))
        with transaction(conn):
            conn.executemany("UPDATE rules SET load_error = ? WHERE id = ?", updates)

    def _compile(self, rule_id: str, yaml_text: str, table: str) -> CompiledRule | str:
        key = (rule_id, table)
        with self._lock:
            if key not in self._compiled:
                try:
                    self._compiled[key] = compile_detection(yaml_text, table)
                except CompileError as exc:
                    self._compiled[key] = str(exc)
            return self._compiled[key]

    def set_enabled(
        self, conn: sqlite3.Connection, rule_id: str, enabled: bool, actor: str | None
    ) -> None:
        with transaction(conn):
            conn.execute(
                "UPDATE rules SET enabled = ?, updated_by = ? WHERE id = ?",
                (int(enabled), actor, rule_id),
            )

    def compiled_for(self, conn: sqlite3.Connection, rule_id: str) -> list[CompiledRule | str]:
        row = conn.execute(
            "SELECT yaml, logsource, kind FROM rules WHERE id = ?", (rule_id,)
        ).fetchone()
        if row is None or row["kind"] != "detection":
            return []
        tables = tables_for(json.loads(row["logsource"]), table_catalog(conn))
        return [self._compile(rule_id, row["yaml"], t) for t in tables]

    # ---------------------------------------------------------------- running

    def _runnable(self, conn: sqlite3.Connection, rule_id: str | None = None) -> list[sqlite3.Row]:
        sql = (
            "SELECT id, title, level, tags, yaml, logsource FROM rules WHERE kind = 'detection' "
            "AND load_error IS NULL"
        )
        if rule_id is None:
            return conn.execute(sql + " AND enabled = 1").fetchall()
        return conn.execute(sql + " AND id = ?", (rule_id,)).fetchall()

    def _ensure_columns(self, conn: sqlite3.Connection, compiled: CompiledRule) -> None:
        """A rule may reference fields this table has never seen; add them as empty
        columns so the query runs (and NOT/exists conditions behave correctly)."""
        store = EventStore(conn)
        existing = store.table_columns(compiled.table)
        missing = [f for f in compiled.fields if f.lower() not in existing]
        if missing:
            with transaction(conn):
                for f in missing:
                    conn.execute(
                        f"ALTER TABLE {quote_ident(compiled.table)} "
                        f"ADD COLUMN {quote_ident(f)} TEXT COLLATE NOCASE"
                    )

    def _matches(
        self, conn: sqlite3.Connection, compiled: CompiledRule, lo: int, hi: int
    ) -> list[Match]:
        cursor = conn.execute(
            f"SELECT * FROM ({compiled.sql}) WHERE {ID} BETWEEN ? AND ?",
            (lo, hi),
        )
        out = []
        for row in cursor:
            out.append(Match(compiled.table, row[ID], row["tl_ts"], entities_from_row(row)))
        return out

    def _run_rule(
        self,
        conn: sqlite3.Connection,
        rule: sqlite3.Row,
        ranges: dict[str, list[tuple[int, int]]],
        origin: str,
        report: RunReport,
    ) -> None:
        catalog = table_catalog(conn)
        existing = set(EventStore(conn).event_tables())
        info = RuleInfo(
            rule["id"], rule["title"], rule["level"] or "medium", json.loads(rule["tags"])
        )
        window = self.settings.alert_throttle_minutes * 60_000
        for table in tables_for(json.loads(rule["logsource"]), catalog):
            if table not in ranges or table not in existing:
                continue
            compiled = self._compile(rule["id"], rule["yaml"], table)
            if isinstance(compiled, str):
                report.errors[rule["id"]] = compiled
                continue
            self._ensure_columns(conn, compiled)
            for lo, hi in ranges[table]:  # one range at a time keeps memory bounded
                try:
                    matched = self._matches(conn, compiled, lo, hi)
                except sqlite3.Error as exc:
                    report.errors[rule["id"]] = f"query failed on {table}: {exc}"
                    log.warning("rule query failed", extra={"rule": rule["id"], "error": str(exc)})
                    break
                if matched:
                    with transaction(conn):
                        report.result.merge(record_matches(conn, info, matched, window, origin))
        report.rules_run += 1

    def run_ranges(
        self, conn: sqlite3.Connection, chunks: Iterable[tuple[str, int, int]]
    ) -> RunReport:
        """Detection on newly ingested rows (``(table, min_id, max_id)`` chunks)."""
        register_functions(conn)
        ranges: dict[str, list[tuple[int, int]]] = {}
        for table, lo, hi in chunks:
            ranges.setdefault(table, []).append((lo, hi))
        report = RunReport()
        if not ranges:
            return report
        for rule in self._runnable(conn):
            self._run_rule(conn, rule, ranges, "ingest", report)
        return report

    def retro_hunt(self, conn: sqlite3.Connection, rule_id: str) -> RunReport:
        """Run one rule (enabled or not) over every stored event."""
        register_functions(conn)
        report = RunReport()
        rows = self._runnable(conn, rule_id)
        if not rows:
            report.errors[rule_id] = "rule not found, not a detection rule, or has errors"
            return report
        ranges: dict[str, list[tuple[int, int]]] = {}
        for table in EventStore(conn).event_tables():
            lo, hi = conn.execute(
                f"SELECT min({ID}), max({ID}) FROM {quote_ident(table)}"
            ).fetchone()
            if lo is None:
                continue
            ranges[table] = [
                (s, min(hi, s + RETRO_CHUNK - 1)) for s in range(lo, hi + 1, RETRO_CHUNK)
            ]
        self._run_rule(conn, rows[0], ranges, "retro", report)
        return report

    # ---------------------------------------------------------------- rule tests

    def run_tests(self, conn: sqlite3.Connection, rule_id: str | None = None) -> list[Any]:
        """Run the tp/tn fixtures of every rule (or one) and store the outcome."""
        from threatlens.detection.testing import run_rule_test  # noqa: PLC0415 - import cycle

        sql = "SELECT * FROM rules" + (" WHERE id = ?" if rule_id else "")
        rows = conn.execute(sql, (rule_id,) if rule_id else ()).fetchall()
        dirs = rule_test_dirs(self.settings)
        results = []
        for row in rows:
            lr = LoadedRule(
                id=row["id"],
                title=row["title"],
                kind=row["kind"],
                origin=row["origin"],
                path=row["path"],
                yaml=row["yaml"],
                sha256=row["sha256"],
                logsource=json.loads(row["logsource"]),
                load_error=row["load_error"],
            )
            results.append(run_rule_test(lr, dirs))
        now = now_ms()
        with transaction(conn):
            conn.executemany(
                "UPDATE rules SET test_status = ?, test_message = ?, tested_at = ? WHERE id = ?",
                [(r.status, "; ".join(r.messages) or None, now, r.rule_id) for r in results],
            )
        return results
