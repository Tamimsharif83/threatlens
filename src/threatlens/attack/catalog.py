"""The bundled MITRE ATT&CK Enterprise technique list (offline).

Generated by ``scripts/gen_attack_techniques.py`` from MITRE's STIX data; see
the ``version`` / ``source_sha256`` fields of the JSON file for provenance.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from importlib import resources
from typing import Any

TECHNIQUE_TAG = re.compile(r"^attack\.(t\d{4}(?:\.\d{3})?)$", re.IGNORECASE)
# Tactic tags used by older Sigma rules that ATT&CK has since renamed or split.
LEGACY_TACTICS = {"defense-evasion": "Defense Evasion (legacy)"}


@dataclass(frozen=True, slots=True)
class Tactic:
    id: str
    shortname: str
    name: str


@dataclass(frozen=True, slots=True)
class Technique:
    id: str
    name: str
    tactics: tuple[str, ...]
    parent: str | None


@dataclass(frozen=True, slots=True)
class Catalog:
    version: str
    attribution: str
    tactics: tuple[Tactic, ...]
    techniques: dict[str, Technique]

    def technique(self, tid: str) -> Technique | None:
        return self.techniques.get(tid.upper())

    def name(self, tid: str) -> str:
        t = self.technique(tid)
        return t.name if t else "unknown technique"

    def tactic_names(self) -> dict[str, str]:
        return {t.shortname: t.name for t in self.tactics} | LEGACY_TACTICS

    def subtechniques(self, parent: str) -> list[Technique]:
        return [t for t in self.techniques.values() if t.parent == parent]


@lru_cache(maxsize=1)
def load() -> Catalog:
    raw: dict[str, Any] = json.loads(
        resources.files("threatlens.attack")
        .joinpath("data/enterprise-attack.json")
        .read_text(encoding="utf-8")
    )
    techniques = {
        t["id"]: Technique(t["id"], t["name"], tuple(t["tactics"]), t["parent"])
        for t in raw["techniques"]
    }
    return Catalog(
        version=str(raw["version"]),
        attribution=str(raw["attribution"]),
        tactics=tuple(Tactic(t["id"], t["shortname"], t["name"]) for t in raw["tactics"]),
        techniques=techniques,
    )


def techniques_in_tags(tags: list[str]) -> list[str]:
    """``attack.t1110.001`` -> ``T1110.001`` (order kept, duplicates removed)."""
    out: list[str] = []
    for tag in tags:
        m = TECHNIQUE_TAG.match(tag.strip())
        if m and m.group(1).upper() not in out:
            out.append(m.group(1).upper())
    return out
